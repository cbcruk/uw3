/**
 * 압류(leeway) — 뱃머리 방향과 실제 진행 방향의 어긋남 (SHAPE P9).
 *
 * **형태는 근거가 있다.** 여러 출처가 일치한다:
 *   - 클로스홀드에서 최대이고, 바람이 뒤로 갈수록 줄어 순풍에서는 사실상 0이다
 *   - 바람이 셀수록 커진다
 *   - 모든 범선이 압류를 지녔다. "압류가 없는 배"가 아니라 "덜 밀리는 배"가
 *     좋은 배라고 불렸다
 *   - 라틴돛은 바람에 가깝게 붙지만 클로스홀드에서 양력의 대부분이 **옆으로 미는
 *     힘**이고, 그것을 선체의 측면적이 받아내야 한다 — 못 받아내면 압류가 된다
 *
 * **크기는 저작이다.** 현대 요트는 클로스홀드 3~5°, 강풍의 소형 요트가 10°까지
 * 밀린다고 하고, 항해 실무는 클로스홀드에 10~15°를 잡으라고 한다. 클리퍼는
 * 강풍에서 20~30°까지 갔다. 캐러벨은 흘수가 얕아 측면적이 작으므로 현대 요트보다
 * 나쁜 쪽이다. 그 사이 어디인지를 짚을 사료를 아직 못 봤다.
 *
 * 위 근거는 전부 **웹 검색 요약**에서 왔고 원문을 열지 못했다 (이 세션의 egress
 * 정책이 임의 호스트를 막는다). 그래서 `measured`가 아니라 `qualitative`다 —
 * 형태는 대고, 수는 못 댄다.
 *
 * **경고**: 이 값을 볼타 두 마르가 재현되도록 조정하면 SPEC 6 위반이다.
 * 구조를 넣고 결과를 보는 것까지가 이 표의 일이다.
 */
